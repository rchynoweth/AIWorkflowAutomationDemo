def _live_workflow(client) -> None:
    try:
        status = client.backend()
    except ApiError:
        return
    if not status.get("available") or not status.get("runs"):
        return
    run = status["runs"][0]
    tasks = ", ".join(f"{k}: {ui.nice(v)}" for k, v in run["tasks"].items())
    st.markdown(f"**Last run of `lsi-pipeline`:** {ui.nice(run['state'])} at {run.get('start_time')} UTC "
                f"({run.get('duration_s')} s) - {tasks}")
    if run.get("run_page_url"):
        st.link_button("Open this run in Databricks", run["run_page_url"], icon=":material/open_in_new:")


def render() -> None:
    client = get_client()
    st.markdown("## How it works")
    ui.notes("how_it_works")
    st.markdown("**Databricks is the backend.** One serverless workflow turns servicing exports into governed facts, "
                "uses AI to explain them, and has an agent investigate the loans that matter. The app only reads "
                "the results and calls the agent on demand.")
    st.graphviz_chart(DIAGRAM, use_container_width=True)
    _live_workflow(client)

    st.markdown("### Where the AI is created")
    st.dataframe(pd.DataFrame(AI_PLACES, columns=["AI output", "Created in", "How", "Stored in"]),
                 hide_index=True, use_container_width=True)
    st.caption("Input data is synthetic (it stands in for servicing-platform exports). Every AI output is real: "
               "generated by Claude on Databricks.")

    st.markdown("### The agent")
    st.markdown("- Deployed with the **Mosaic AI Agent Framework**, registered in **Unity Catalog**, served on "
                "**Model Serving**.\n"
                "- Its tools are **17 Unity Catalog SQL functions**; it decides which to call.\n"
                "- Read-only: it explains and recommends. People decide. Every call is traced in **MLflow**.\n"
                "- See it live on the **The Agent** page.")

    st.markdown("### Databricks components")
    st.dataframe(pd.DataFrame(COMPONENTS, columns=["Component", "Role in this solution"]), hide_index=True,
                 use_container_width=True)

    st.markdown("### Open it in Databricks")
    try:
        inv = client.resources()
    except ApiError:
        inv = {}
    if inv.get("available"):
        df = pd.DataFrame(inv["items"])[["resource", "what_it_is", "url"]]
        st.dataframe(df.rename(columns={"resource": "Resource", "what_it_is": "What it is", "url": "Link"}),
                     hide_index=True, use_container_width=True,
                     column_config={"Link": st.column_config.LinkColumn(display_text="Open")})
    else:
        st.caption(inv.get("reason", "Links appear when the app runs in Databricks."))
